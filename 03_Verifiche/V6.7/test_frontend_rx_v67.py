#!/usr/bin/env python3
import unittest,csv,json,math,random,importlib.util,sys
from pathlib import Path
HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
spec=importlib.util.spec_from_file_location('mdl_v67',HERE/'analizza_frontend_v67.py')
mdl=importlib.util.module_from_spec(spec);spec.loader.exec_module(mdl)
with (ROOT/'01_Specifiche/V6.7/NETLIST_PIN_RX_FRONTEND_V6.7.csv').open(encoding='utf8') as f: PINS=list(csv.DictReader(f))
with (ROOT/'07_Componenti/BOM_FRONTEND_RX_V6.7.csv').open(encoding='utf8') as f: BOM=list(csv.DictReader(f))
with (ROOT/'02_Piano_Frequenze/V6.4/PIANO_PLL_LO_270_RX_V6.4.csv').open(encoding='utf8') as f: PLANS=list(csv.DictReader(f))
with (HERE/'RISULTATI_ANALISI_FRONTEND_V6.7.json').open(encoding='utf8') as f: RESULTS=json.load(f)
with (HERE/'BILANCIO_270_RX_V6.7.csv').open(encoding='utf8') as f: MAP=list(csv.DictReader(f))

def present(ref,pin,net):return any(d['ref']==ref and d['pin_or_terminal']==pin and d['net']==net for d in PINS)

class FrontendV67(unittest.TestCase):
    def test_001_frequency_count(self):self.assertEqual(len(PLANS),270)
    def test_002_sim_frequency_count(self):self.assertEqual(len(MAP),270)
    def test_003_frequency_alignment(self):self.assertEqual([(r['banda'],r['canale']) for r in MAP],[(r['banda'],r['canale']) for r in PLANS])
    def test_004_RF_range(self):self.assertTrue(all(25_615_000<=int(r['rf_hz'])<=28_305_000 for r in MAP))
    def test_005_image_offset(self):self.assertTrue(all(int(r['image_hz'])-int(r['rf_hz'])==21_390_000 for r in MAP))
    def test_006_IF(self):self.assertTrue(all(int(r['lo_hz'])-int(r['rf_hz'])==10_695_000 for r in MAP))
    def test_007_image_stopband(self):self.assertTrue(all(39e6<=int(r['image_hz'])<=900e6 for r in MAP))
    def test_008_all_rx_in_filter(self):self.assertTrue(all(24e6<=int(r['rf_hz'])<=31e6 for r in MAP))
    def test_009_band_counts(self):self.assertEqual({b:sum(r['banda']==b for r in MAP) for b in 'ABCDEF'},{b:45 for b in 'ABCDEF'})
    def test_010_pin_uniqueness(self):self.assertEqual(len({(x['ref'],x['pin_or_terminal']) for x in PINS}),len(PINS))
    def test_011_unique_BOM_refs(self):self.assertEqual(len(set(x['ref'] for x in BOM)),len(BOM))
    def test_012_BOM_netlist_coverage(self):self.assertEqual(set(x['ref'] for x in BOM),set(x['ref'] for x in PINS))
    def test_013_F501_input(self):self.assertTrue(present('F501','1','RX_ANT_PRE'))
    def test_014_F501_output(self):self.assertTrue(present('F501','8','RX_FILTER_OUT'))
    def test_015_F501_ground_pins(self):self.assertTrue(all(present('F501',str(x),'GND_RF') for x in range(2,8)))
    def test_016_ADL_input(self):self.assertTrue(present('U101','1','RX_LNA_IN'))
    def test_017_ADL_ground(self):self.assertTrue(present('U101','2','GND_RF'))
    def test_018_ADL_paddle_ground(self):self.assertTrue(present('U101','PAD','GND_RF'))
    def test_019_ADL_output_bias(self):self.assertTrue(present('U101','3','RX_LNA_OUT_BIASED'))
    def test_020_choke(self):self.assertTrue(present('L701','2','RX_LNA_OUT_BIASED'))
    def test_021_DC_block_input(self):self.assertTrue(present('C701','2','RX_LNA_IN'))
    def test_022_DC_block_output(self):self.assertTrue(present('C702','1','RX_LNA_OUT_BIASED'))
    def test_023_cap_power_three(self):self.assertTrue(all(present(x,'1','5V_RF_RX_DECOUPLED') for x in ('C703','C704','C705')))
    def test_024_cap_gnd_three(self):self.assertTrue(all(present(x,'2','GND_RF') for x in ('C703','C704','C705')))
    def test_025_pad_series(self):self.assertTrue(present('R701','1','RX_PAD_IN') and present('R701','2','RX_TO_MIXER'))
    def test_026_pad_shunts(self):self.assertTrue(present('R702','2','GND_RF') and present('R703','2','GND_RF'))
    def test_027_mixer_output(self):self.assertTrue(present('J702','SIG','RX_TO_MIXER'))
    def test_028_power_is_switched_placeholder(self):self.assertTrue(present('J703','1','5V_RF_RX_DECOUPLED'))
    def test_029_no_TX_nets(self):self.assertFalse(any('TX_' in r['net'] or 'RF_PA' in r['net'] for r in PINS))
    def test_030_no_TX_permission(self):self.assertFalse(RESULTS['tx_enabled'])
    def test_031_no_FAB_release(self):self.assertFalse(RESULTS['fab_released'])
    def test_032_ESD_cap_effect(self):self.assertTrue(0<mdl.esd_s21_loss(27e6,.2e-12)<0.001)
    def test_033_ESD_is_monotonic(self):self.assertLess(mdl.esd_s21_loss(27e6,.2e-12),mdl.esd_s21_loss(27e6,1e-12))
    def test_034_ESD_frequency(self):self.assertLess(mdl.esd_s21_loss(25.6e6,.2e-12),mdl.esd_s21_loss(28.3e6,.2e-12))
    def test_035_pad6_loss(self):self.assertAlmostEqual(mdl.pi_attenuator()[0],6,delta=.02)
    def test_036_pad_matching(self):self.assertGreater(mdl.pi_attenuator()[1],40)
    def test_037_default_gain(self):self.assertAlmostEqual(mdl.front_metrics()[1],9.9,places=8)
    def test_038_default_noise(self):self.assertAlmostEqual(mdl.front_metrics()[0],4.70411,places=4)
    def test_039_pad_gain(self):self.assertLess(mdl.front_metrics(pad=6)[1],mdl.front_metrics()[1])
    def test_040_pad_noise(self):self.assertGreater(mdl.front_metrics(pad=6)[0],mdl.front_metrics()[0])
    def test_041_filter_noise(self):self.assertGreater(mdl.front_metrics(filter_loss=2.5)[0],mdl.front_metrics(filter_loss=1.3)[0])
    def test_042_LNA_noise(self):self.assertGreater(mdl.front_metrics(lna_nf=4)[0],mdl.front_metrics(lna_nf=3)[0])
    def test_043_mixer_approx(self):self.assertGreater(mdl.front_metrics(mixer_loss=6)[0],mdl.front_metrics(mixer_loss=5)[0])
    def test_044_image_relative(self):self.assertEqual(RESULTS['image_rejection']['relative_worst_case_lower_bound_db_if_equal_other_gain'],17.5)
    def test_045_image_not_certified(self):self.assertFalse(RESULTS['image_rejection']['target_certified'])
    def test_046_thermal_typ(self):self.assertAlmostEqual(RESULTS['adl_thermal_approx']['dc_power_typ_w'],.485)
    def test_047_thermal_max(self):self.assertGreater(RESULTS['adl_thermal_approx']['estimated_tj_at_85c_115ma_and_30p7K_W_c'],100)
    def test_048_MonteCarlo_count(self):self.assertEqual(RESULTS['monte_carlo']['samples'],20000)
    def test_049_MC_minmax(self):self.assertLess(RESULTS['monte_carlo']['nf_min_db'],RESULTS['monte_carlo']['nf_max_db'])
    def test_050_MC_gain(self):self.assertLess(RESULTS['monte_carlo']['gain_min_db'],RESULTS['monte_carlo']['gain_max_db'])
    def test_051_BOM_DNI(self):self.assertIn('DNI',next(x for x in BOM if x['ref']=='D701')['qualification'])
    def test_052_BOM_legacy_U101(self):self.assertIn('LEGACY',next(x for x in BOM if x['ref']=='U101')['qualification'])
    def test_053_test_points_DNI(self):self.assertEqual(next(x for x in BOM if x['ref']=='TP701')['qualification'],'DNI')
    def test_054_no_native_false_claims(self):self.assertIn('native_KiCad_ERC',RESULTS['not_run'])
    def test_055_170_sense_channel_csv(self):self.assertEqual(set(x['status'] for x in MAP),{'MODELLO_E_IPOTESI_NON_DATI_MISURATI'})
    def test_056_270_unique_freq_per_band_channel(self):self.assertEqual(len({(x['banda'],x['canale']) for x in MAP}),270)
    def test_057_270_loop_all_finite(self):
        for r in MAP:
            with self.subTest(rf=r['rf_hz']):
                self.assertTrue(math.isfinite(float(r['front_nf_db_friis_assunto'])))
    def test_058_270_positive_image_gap(self):
        for r in MAP:
            with self.subTest(rf=r['rf_hz']):self.assertGreater(int(r['image_hz']),int(r['lo_hz']))
    def test_059_270_interpolation_range(self):self.assertTrue(all(16.5<=float(r['adl_gain_interp_db_assunto'])<=16.7 for r in MAP))
    def test_060_270_esd_loss_not_undercount(self):self.assertTrue(all(float(r['esd_ideal_il_0p2pf_db'])>=0 for r in MAP))

if __name__=='__main__':
    unittest.main(verbosity=1)
